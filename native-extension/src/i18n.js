export function t(value,locale=language){const key=Object.hasOwn(MESSAGES,value)?value:reverse.get(value);return key?(locale==='zh-CN'?key:MESSAGES[key]):value;}
// Only extension-owned chrome is passed here; content roots are excluded.
// Exact dictionary matches avoid altering arbitrary article/provider strings.
export function localizeUI(root,locale=language){
 if(!root)return;const document=root.ownerDocument||root;
 const excluded=node=>node.parentElement?.closest('[translate="no"],.pk-ai-summary,.pk-ai-map,.pk-ai-search-results,.pk-ai-chapter-title,.pk-ai-chapter-points');
 const walker=document.createTreeWalker(root,4);let node;while((node=walker.nextNode()))if(!excluded(node)){const text=t(node.data,locale);if(text!==node.data)node.data=text;}
 for(const element of [root,...root.querySelectorAll('*')])if(element.nodeType===1&&!element.closest('[translate="no"],.pk-ai-summary,.pk-ai-map,.pk-ai-search-results'))for(const attr of ['title','aria-label','placeholder'])if(element.hasAttribute(attr)){const value=element.getAttribute(attr);const text=t(value,locale);if(text!==value)element.setAttribute(attr,text);}
}

